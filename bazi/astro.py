def _series(terms, tau):
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)


def solar_longitude(jde: float) -> float:
    """太陽視黃經（度，0–360），輸入係力學時 TT 嘅儒略日。

    地球日心黃經（VSOP87）+ 180° = 太陽地心黃經，再轉 FK5 參考系，
    加黃經章動，減光行差。
    """
    tau = (jde - 2451545.0) / 365250.0
    l = (_series(L0, tau) + _series(L1, tau) * tau + _series(L2, tau) * tau**2
         + _series(L3, tau) * tau**3 + _series(L4, tau) * tau**4
         + _series(L5, tau) * tau**5) / 1e8          # 弧度
    theta = math.degrees(l) + 180.0                   # 太陽地心黃經

    t = (jde - 2451545.0) / 36525.0
    # VSOP87 -> FK5（Meeus 32.3）
    theta -= 0.09033 / 3600.0

    # 黃經章動主項（Meeus 22）
    omega = (125.04452 - 1934.136261 * t) * RAD
    lsun = (280.4665 + 36000.7698 * t) * RAD
    lmoon = (218.3165 + 481267.8813 * t) * RAD
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * lsun)
            - 0.23 * math.sin(2 * lmoon) + 0.21 * math.sin(2 * omega)) / 3600.0

    # 光行差。R 用 Meeus 25.5 嘅橢圓公式，夠準 —— R 由 0.983 到 1.017,
    # 對光行差嘅影響得 0.35 角秒。
    m = (357.52911 + 35999.05029 * t - 0.0001537 * t * t) * RAD
    e = 0.016708634 - 0.000042037 * t - 0.0000001267 * t * t
    c = ((1.914602 - 0.004817 * t - 0.000014 * t * t) * math.sin(m)
         + (0.019993 - 0.000101 * t) * math.sin(2 * m)
         + 0.000289 * math.sin(3 * m))
    v = math.degrees(m) + c
    r = 1.000001018 * (1 - e * e) / (1 + e * math.cos(v * RAD))
    aberr = -20.4898 / r / 3600.0

    return (theta + dpsi + aberr) % 360.0


def term_time(year: int, index: int) -> float:
    """第 index 個節氣（0 = 立春，黃經 315°）喺邊個時刻，回傳 UT 儒略日。

    由估算值開始，用割線法收斂到黃經啱啱好等於目標值。
    """
    target = (315 + index * 15) % 360
    # 立春大約 2 月 4 日；之後每個節氣約隔 15.22 日。
    guess = jd_from(year, 2, 4.0) + index * 15.2184
    if index >= 22:               # 小寒大寒喺下一個公曆年
        pass
    jde = guess + delta_t(year) / 86400.0

    for _ in range(40):
        lam = solar_longitude(jde)
        diff = (lam - target + 180) % 360 - 180
        if abs(diff) < 1e-8:
            break
        jde -= diff * 365.2422 / 360.0      # 太陽每日行約 0.9856°
    return jde - delta_t(year) / 86400.0    # TT -> UT


def term_hkt(year: int, index: int) -> tuple[int, int, int, int]:
    """節氣喺香港時間（UTC+8）嘅 年、月、日、分鐘（由 00:00 起計）。

    先將儒略日四捨五入到最接近嗰分鐘，再轉公曆 —— 唔好反過嚟。
    之前係先轉公曆再 round 分鐘，撞正午夜嗰陣（1923 雨水啱啱好
    20 日 00:00:00）會 round 到 1440 分鐘，跟住要特別處理，而嗰段
    特別處理將佢推多咗一日。四捨五入行先就冇呢個 case。
    """
    jd = term_time(year, index) + 8.0 / 24.0
    jd = round(jd * 1440.0) / 1440.0          # 對齊到分鐘
    y, m, d = cal_from(jd)
    day = int(math.floor(d + 1e-9))
    minutes = int(round((d - day) * 1440.0))
    return y, m, day, minutes
