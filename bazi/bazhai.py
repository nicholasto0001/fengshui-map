"""八宅：本命卦，同埋邊啲坐向合。

點解揀呢個，唔係「八字五行配區」：

五行配方位係有傳統根據嘅（喜用神屬水 → 宜北方）。但「五行 → 香港邊個
區」冇任何傳統依據，係砌出嚟。講「你八字屬水，啱住沙田」係作嘅。

八宅唔同。本命卦由出生年（立春為界）同性別推出，**完全確定性**，冇一
步要判斷；東四命配東四宅、西四命配西四宅亦都係寫喺書入面嘅規矩。而
「呢幢樓坐咩向咩」我哋有 84,720 幢嘅數據。

所以呢條鏈每一段都有根據：
    出生年 + 性別 → 本命卦 → 東四／西四 → 合嘅坐向 → 我哋嘅樓宇數據

而全香港冇第二個人接得埋最後嗰段，因為冇人有逐幢樓嘅坐向。
"""
from __future__ import annotations

# 卦數 -> 卦名。5 唔對應任何一卦，男寄坤、女寄艮。
GUA = {1: "坎", 2: "坤", 3: "震", 4: "巽", 6: "乾", 7: "兌", 8: "艮", 9: "離"}
EAST = {"坎", "離", "震", "巽"}          # 東四命 / 東四宅
WEST = {"乾", "坤", "艮", "兌"}          # 西四命 / 西四宅

# 每一卦嘅方位。呢個係定義，唔係推算。
GUA_DIR = {"坎": "北", "離": "南", "震": "東", "巽": "東南",
           "乾": "西北", "坤": "西南", "艮": "東北", "兌": "西"}

# 二十四山 -> 八方。一卦管三山。
SHAN_DIR = {
    "壬": "北", "子": "北", "癸": "北",
    "丑": "東北", "艮": "東北", "寅": "東北",
    "甲": "東", "卯": "東", "乙": "東",
    "辰": "東南", "巽": "東南", "巳": "東南",
    "丙": "南", "午": "南", "丁": "南",
    "未": "西南", "坤": "西南", "申": "西南",
    "庚": "西", "酉": "西", "辛": "西",
    "戌": "西北", "乾": "西北", "亥": "西北",
}
DIR_GUA = {v: k for k, v in GUA_DIR.items()}

# 八宅嘅遊年（四吉四凶）唔係打出嚟，係由變爻推出嚟。
#
# 打一張 8 × 8 = 64 格嘅表落去，打錯一格係冇人睇得出嘅 —— 而嗰格會令
# 一個人以為自己間屋係吉方。所以用返規則：由本命卦出發，爻變邊幾爻,
# 得出邊一卦，就係邊一個遊年星。
#
#     上爻變     生氣      中下爻變   天醫
#     中爻變     絕命      上中爻變   五鬼
#     下爻變     禍害      上下爻變   六煞
#     三爻全變   延年      唔變       伏位
#
# 八卦嘅爻（由下數上，1 陽 0 陰）：
TRIGRAM = {
    (1, 1, 1): "乾", (1, 1, 0): "兌", (1, 0, 1): "離", (1, 0, 0): "震",
    (0, 1, 1): "巽", (0, 1, 0): "坎", (0, 0, 1): "艮", (0, 0, 0): "坤",
}
BITS = {v: k for k, v in TRIGRAM.items()}
# 變邊幾爻（0 = 下爻，1 = 中爻，2 = 上爻）-> 遊年星
CHANGE = {
    (): "伏位", (2,): "生氣", (1,): "絕命", (0,): "禍害",
    (0, 1): "天醫", (1, 2): "五鬼", (0, 2): "六煞", (0, 1, 2): "延年",
}


def _luck_table() -> dict:
    out = {}
    for gua, bits in BITS.items():
        t = {}
        for flips, star in CHANGE.items():
            b = list(bits)
            for f in flips:
                b[f] ^= 1
            t[GUA_DIR[TRIGRAM[tuple(b)]]] = star
        out[gua] = t
    return out


LUCK = _luck_table()
GOOD = ("生氣", "天醫", "延年", "伏位")


def ming_gua(bazi_year: int, male: bool) -> str:
    """本命卦。

    年份要用**八字年**（立春為界），唔係公曆年 —— 一月同二月頭出世嘅人
    屬上一年。

    算法：年份數字加到剩一個位（S）。
        男 = 11 - S，大過 9 就減 9
        女 =  4 + S，大過 9 就減 9
    五男寄坤、五女寄艮。
    """
    s = bazi_year
    while s > 9:
        s = sum(int(c) for c in str(s))
    n = (11 - s) if male else (4 + s)
    while n > 9:
        n -= 9
    if n == 5:
        n = 2 if male else 8
    return GUA[n]


def group(gua: str) -> str:
    return "東四" if gua in EAST else "西四"


def suits(gua: str, facing_shan: str) -> tuple[str, bool]:
    """呢個坐向對呢個命卦嚟講係咩？回傳（遊年星, 係咪吉）。

    以**向**論。陽宅以向首納氣，所以配嘅係樓宇向邊，唔係坐邊。
    """
    d = SHAN_DIR.get(facing_shan)
    if not d:
        return ("", False)
    star = LUCK[gua][d]
    return (star, star in GOOD)


def good_dirs(gua: str) -> list:
    """四個吉方，由最吉排落去。"""
    order = {"生氣": 0, "天醫": 1, "延年": 2, "伏位": 3}
    return sorted((d for d, s in LUCK[gua].items() if s in GOOD),
                  key=lambda d: order[LUCK[gua][d]])
